"""Emit rtl/mlkem_prog_pkg.sv (micro-program ROM) from isa.py."""
import isa
LN = {v: k for k, v in vars(isa).items() if k.startswith("L_")} if False else {}
LANE_NAMES = {0: "L_DK", 96: "L_EK", 192: "L_RHO", 196: "L_HEK", 200: "L_Z", 204: "L_CT", 300: "L_CT2",
              396: "L_D", 400: "L_MSG", 404: "L_KR", 412: "L_SIGMA", 420: "L_KBAR"}
SLOT = ["SA", "SP", "S0", "S1", "E0", "E1", "T0", "T1", "U0", "U1", "SV", "SE2", "SW"]
def lane(v):
    if v in LANE_NAMES: return LANE_NAMES[v]
    best = max(k for k in LANE_NAMES if k <= v); return f"{LANE_NAMES[best]}+{v-best}"
def fmt(i):
    z = "9'd0"
    la = f"9'({lane(i['la'])})" if i['la'] else z
    lb = f"9'({lane(i['lb'])})" if i['lb'] else z
    return (f"mk(OP_{i['op']:<7}, {SLOT[i['sa']]:>3}, {SLOT[i['sb']]:>3}, {SLOT[i['sd']]:>3}, "
            f"{la:>14}, {lb:>14}, 9'd{i['n']:<3}, 16'h{i['imm']:04X})")
def build():
    progs = [("KEYGEN", isa.prog_keygen()), ("ENCAPS", isa.prog_encaps()), ("DECAPS", isa.prog_decaps())]
    rows, bases, pc = [], {}, 0
    for name, p in progs:
        bases[name] = pc
        rows.append(f"            // ---------------- {name} ----------------")
        for ins in p.ins:
            c = f"  // {ins['cmt']}" if ins["cmt"] else ""
            rows.append(f"            8'd{pc:<3}: p = {fmt(ins)};{c}")
            pc += 1
    slots = "\n".join(f"    localparam logic [3:0] {n:<3} = 4'd{i};" for i, n in enumerate(SLOT))
    return f'''// ============================================================================
// mlkem_prog_pkg.sv   (generated by model/gen_prog.py - edit isa.py, not this file)
// Micro-programs for ML-KEM-512 KeyGen / Encaps / Decaps.
// mk(op, sa, sb, sd, la, lb, n, imm)
// ============================================================================
package mlkem_prog_pkg;
    import mlkem_pkg::*;

    // poly RAM slots
{slots}

    localparam logic [7:0] PC_KEYGEN = 8'd{bases["KEYGEN"]};
    localparam logic [7:0] PC_ENCAPS = 8'd{bases["ENCAPS"]};
    localparam logic [7:0] PC_DECAPS = 8'd{bases["DECAPS"]};

    function automatic instr_t mk(input opcode_t op, input logic [3:0] sa, input logic [3:0] sb,
                                  input logic [3:0] sd, input logic [8:0] la, input logic [8:0] lb,
                                  input logic [8:0] n, input logic [15:0] imm);
        return {{op, sa, sb, sd, la, lb, n, imm}};
    endfunction

    function automatic instr_t prog_rom(input logic [7:0] pc);
        instr_t p;
        case (pc)
{chr(10).join(rows)}
            default: p = mk(OP_END, SA, SA, SA, 9'd0, 9'd0, 9'd0, 16'h0000);
        endcase
        return p;
    endfunction

endpackage
'''
open("../rtl/control/mlkem_prog_pkg.sv", "w").write(build())
