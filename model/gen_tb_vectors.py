"""Emit tb/tb_vectors_pkg.sv : golden ML-KEM-512 vectors from the reference model."""
import ref_mlkem as R
def arr(name, b):
    rows = [", ".join(f"8'h{x:02X}" for x in b[i:i+16]) for i in range(0, len(b), 16)]
    return f"    localparam logic [7:0] {name} [{len(b)}] = '{{\n        " + ",\n        ".join(rows) + "\n    };\n"
cases = [(bytes(range(32)), bytes(range(32, 64)), bytes(range(64, 96))),
         ((3).to_bytes(32, "little"), bytes([0xA5] * 32), bytes([0x3C] * 32))]   # case 1 exercises d1 == q
out = ["// generated by model/gen_tb_vectors.py from the FIPS 203 reference model",
       "package tb_vectors_pkg;", f"    localparam int NCASE = {len(cases)};"]
for i, (d, z, m) in enumerate(cases):
    ek, dk = R.keygen(d, z); K, ct = R.encaps(ek, m)
    bad = bytearray(ct); bad[100] ^= 0x01; bad = bytes(bad)
    kbar = R.decaps(dk, bad); assert kbar != K and R.decaps(dk, ct) == K
    for n, v in (("D", d), ("Z", z), ("M", m), ("EK", ek), ("DK", dk), ("CT", ct), ("K", K), ("CTBAD", bad), ("KBAR", kbar)):
        out.append(arr(f"{n}{i}", v))
out.append("endpackage\n")
open("../tb/tb_vectors_pkg.sv", "w").write("\n".join(out))
